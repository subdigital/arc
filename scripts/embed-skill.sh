#!/bin/sh
# Regenerates Sources/ArcAgentKit/SkillText.swift from skills/arc/SKILL.md.
# The CLI embeds the skill so `arc skill install` works without resource bundles.
set -eu
cd "$(dirname "$0")/.."
{
    echo '// Generated by scripts/embed-skill.sh from skills/arc/SKILL.md. Do not edit by hand.'
    echo ''
    echo 'extension ArcSkill {'
    echo '    static let text = #"""'
    sed 's/^\(.\)/        \1/' skills/arc/SKILL.md
    printf '%s\n' '        """# + "\n"'
    echo '}'
} > Sources/ArcAgentKit/SkillText.swift
